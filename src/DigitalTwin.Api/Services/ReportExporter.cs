using System.Text;
using System.Text.RegularExpressions;
using DocumentFormat.OpenXml;
using DocumentFormat.OpenXml.Packaging;
using D = DocumentFormat.OpenXml.Drawing;
using P = DocumentFormat.OpenXml.Presentation;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace DigitalTwin.Api;

/// <summary>
/// Deterministic export engine. The model writes a report; this service creates real
/// PDF/PPTX/SVG bytes without asking the model to invent binary files.
/// </summary>
public sealed class ReportExporter
{
    public (byte[] Bytes, string Mime, string Extension) Export(string format, string title, string content)
    {
        if (string.IsNullOrWhiteSpace(title) || title.Length > 130) throw new ArgumentException("Title must be 1–130 characters.");
        if (string.IsNullOrWhiteSpace(content) || content.Length > 50_000) throw new ArgumentException("Report must be 1–50,000 characters.");
        return format.ToLowerInvariant() switch
        {
            "md" => (Encoding.UTF8.GetBytes($"# {title}\n\n{content}"), "text/markdown", "md"),
            "pdf" => (CreatePdf(title, content), "application/pdf", "pdf"),
            "pptx" => (CreateSlides(title, content), "application/vnd.openxmlformats-officedocument.presentationml.presentation", "pptx"),
            "svg" => (Encoding.UTF8.GetBytes(CreateDiagram(title, content)), "image/svg+xml", "svg"),
            _ => throw new ArgumentException("Supported formats: md, pdf, pptx, svg.")
        };
    }
    private static string Plain(string input) => Regex.Replace(input, @"(?m)^\s{0,3}(?:#+\s*|[-*]\s*|\d+\.\s*)", "").Replace("**", "").Replace("`", "");

    // Lato lacks emoji glyphs. Use readable text substitutes for decorative icons;
    // Arabic/extended scripts need a suitable font on the machine or bundled by the
    // project owner (not copied into this starter). Never silently disable checking.
    private static string PdfFriendly(string text)
    {
        var replacements = new Dictionary<string, string> {
            ["📌"] = "[Note]", ["✅"] = "[OK]", ["⚠️"] = "[Warning]",
            ["🚀"] = "[Launch]", ["🔒"] = "[Secure]", ["📁"] = "[Folder]",
            ["🧠"] = "[Knowledge]", ["📄"] = "[Document]", ["❌"] = "[Error]"
        };
        foreach (var (key, value) in replacements) text = text.Replace(key, value);
        return Regex.Replace(text, @"[\uD800-\uDBFF][\uDC00-\uDFFF]|[\u2600-\u27BF]|[\uFE0F\u200D]", "[symbol]");
    }

    private static byte[] CreatePdf(string title, string content)
    {
        // Evaluation license is appropriate for this training project; revisit for business deployment.
        QuestPDF.Settings.License = LicenseType.Evaluation;
        // On the local Windows demo, system fonts help with Arabic and accented text.
        // Production deployments should bundle explicit licensed Unicode fonts.
        QuestPDF.Settings.UseSystemFonts = true;
        var paragraphs = PdfFriendly(Plain(content)).Split('\n', StringSplitOptions.TrimEntries);
        return Document.Create(doc =>
        {
            doc.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(42);
                page.DefaultTextStyle(s => s.FontFamily("Lato", "Arial", "Tahoma", "Segoe UI Symbol", "Segoe UI Emoji").FontSize(10).FontColor("#1f2937"));
                page.Header().Column(col =>
                {
                    col.Item().Text("DEVELOPERTWIN  /  ENGINEERING HANDOFF").FontSize(9).FontColor("#6366f1").SemiBold();
                    col.Item().PaddingTop(8).Text(PdfFriendly(title)).FontSize(22).SemiBold();
                    col.Item().PaddingTop(6).LineHorizontal(1).LineColor("#cbd5e1");
                });
                page.Content().PaddingTop(14).Column(col =>
                {
                    col.Spacing(5);
                    foreach (var line in paragraphs.Take(650))
                    {
                        if (string.IsNullOrWhiteSpace(line)) { col.Item().Height(5); continue; }
                        col.Item().Text(line.Length > 700 ? line[..700] + "…" : line).FontSize(10);
                    }
                });
                page.Footer().AlignCenter().Text("Generated by DeveloperTwin · Review all AI-generated findings before sharing").FontSize(8).FontColor("#64748b");
            });
        }).GeneratePdf();
    }

    private static byte[] CreateSlides(string title, string content)
    {
        // A PowerPoint file needs a slide master, slide layout and theme. Reusing our
        // tiny verified template is safer than constructing an incomplete PPTX package.
        var template = Path.Combine(AppContext.BaseDirectory, "Templates", "handoff-template.pptx");
        // dotnet run can execute from the source tree before a Publish operation.
        if (!File.Exists(template))
            template = Path.Combine(Directory.GetCurrentDirectory(), "Templates", "handoff-template.pptx");
        // Open XML updates a ZIP package when the document is disposed.
        // MemoryStream(byte[]) is fixed-capacity and throws when the ZIP grows.
        // Copy into an expandable stream instead.
        using var stream = new MemoryStream();
        var templateBytes = File.ReadAllBytes(template);
        stream.Write(templateBytes, 0, templateBytes.Length);
        stream.Position = 0;
        using (var document = PresentationDocument.Open(stream, true))
        {
            var presentation = document.PresentationPart ?? throw new InvalidDataException("Template lacks a presentation part.");
            var seed = presentation.SlideParts.FirstOrDefault() ?? throw new InvalidDataException("Template lacks its starter slide.");
            var seedSlide = (P.Slide)(seed.Slide ?? throw new InvalidDataException("Starter slide is missing.")).CloneNode(true);
            var seedLayout = seed.SlideLayoutPart ?? throw new InvalidDataException("Template slide layout is missing.");
            var slideIds = presentation.Presentation?.SlideIdList ?? throw new InvalidDataException("Template slide list is missing.");
            var lines = Plain(content).Split('\n').Where(line => !string.IsNullOrWhiteSpace(line)).ToArray();
            var pages = new List<(string Heading, string Body)>{(title, "Project summary and technical handoff\nCreated by DeveloperTwin")};
            foreach (var batch in lines.Chunk(5).Take(16))
                pages.Add((title, string.Join("\n", batch.Select(x => x.Length > 140 ? x[..140] + "…" : x))));
            uint slideId = 257;
            for (var i = 0; i < pages.Count; i++)
            {
                var slidePart = i == 0 ? seed : presentation.AddNewPart<SlidePart>();
                if (i > 0)
                {
                    slidePart.Slide = (P.Slide)seedSlide.CloneNode(true);
                    slidePart.AddPart(seedLayout);
                    slideIds.Append(new P.SlideId { Id = slideId++, RelationshipId = presentation.GetIdOfPart(slidePart) });
                }
                var slide = slidePart.Slide ?? throw new InvalidDataException("Slide is missing.");
                var tree = slide.CommonSlideData?.ShapeTree ?? throw new InvalidDataException("Slide shape tree is missing.");
                tree.Append(TextShape(100U, "Title", pages[i].Heading, 650000, 1400000, 10900000, 900000, 3300));
                tree.Append(TextShape(101U, "Body", pages[i].Body, 650000, 2550000, 11000000, 3300000, 1900));
                slide.Save();
            }
            presentation.Presentation?.Save();
        }
        return stream.ToArray();
    }
    private static P.Shape TextShape(uint id, string name, string text, long x, long y, long width, long height, int fontSize)
    {
        var paragraphs = text.Split('\n').Select(line =>
        {
            var style = new D.RunProperties { Language = "en-US", FontSize = fontSize };
            style.Append(new D.SolidFill(new D.RgbColorModelHex { Val = fontSize > 3000 ? "FFFFFF" : "DEE6FF" }));
            return new D.Paragraph(new D.Run(style,
                    new D.Text(line)),
                new D.EndParagraphRunProperties { Language = "en-US" });
        });
        var body = new P.TextBody(new D.BodyProperties { Wrap = D.TextWrappingValues.Square }, new D.ListStyle());
        foreach (var paragraph in paragraphs) body.Append(paragraph);
        return new P.Shape(
            new P.NonVisualShapeProperties(
                new P.NonVisualDrawingProperties { Id = id, Name = name },
                new P.NonVisualShapeDrawingProperties(),
                new P.ApplicationNonVisualDrawingProperties()),
            new P.ShapeProperties(new D.Transform2D(new D.Offset { X = x, Y = y }, new D.Extents { Cx = width, Cy = height }),
                new D.PresetGeometry(new D.AdjustValueList()) { Preset = D.ShapeTypeValues.Rectangle }, new D.NoFill()),
            body);
    }

    private static string CreateDiagram(string title, string content)
    {
        string Xml(string s) => System.Security.SecurityElement.Escape(s) ?? "";
        var headings = content.Split('\n').Where(x => x.TrimStart().StartsWith('#')).Take(4)
            .Select(x => Regex.Replace(x.Trim(), "^#+\\s*", "")).ToArray();
        if (headings.Length == 0) headings = ["Input / Requirements", "Agent and tools", "Architecture findings", "Handoff output"];
        var boxes = new StringBuilder();
        for (var i = 0; i < headings.Length; i++)
        {
            var x = 50 + i * 265;
            boxes.Append($"<rect x='{x}' y='130' width='220' height='100' rx='15' fill='#26375a' stroke='#7c83f6' stroke-width='2'/>" +
                $"<text x='{x + 110}' y='185' text-anchor='middle' fill='white' font-size='15'>{Xml(headings[i].Length > 24 ? headings[i][..24] + "…" : headings[i])}</text>");
            if (i > 0) boxes.Append($"<path d='M{x - 43} 181h32l-9 -7m9 7l-9 7' fill='none' stroke='#8295bb' stroke-width='2' />");
        }
        var width = 100 + headings.Length * 265;
        return $"<svg xmlns='http://www.w3.org/2000/svg' width='{width}' height='310' viewBox='0 0 {width} 310'>" +
            $"<rect width='100%' height='100%' fill='#0c1222'/><text x='50' y='65' fill='#eef2ff' font-family='Arial' font-size='25' font-weight='bold'>{Xml(title)}</text>" +
            $"<text x='50' y='92' fill='#a8b8d6' font-family='Arial' font-size='13'>DeveloperTwin · Handoff overview (diagram is a simplified illustration)</text>" +
            $"<g font-family='Arial'>{boxes}</g></svg>";
    }
}
